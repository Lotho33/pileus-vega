// Renders src/gradients/defs.json into 256-step PNG ramps (one colour, alpha
// following the stops) plus src/gradients/assets.ts mapping names to them.
// Stretched by the GPU, one ramp replaces hundreds of band Views and blends
// smoothly. Run after editing defs.json: node scripts/gen-gradients.mjs
import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {deflateSync} from 'node:zlib';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'src/gradients');
const defs = JSON.parse(readFileSync(join(dir, 'defs.json'), 'utf8'));
const STEPS = 256;

const CRC = new Uint32Array(256).map((_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
const crc32 = buf => {
  let c = 0xffffffff;
  for (const b of buf) c = CRC[(c ^ b) & 255] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
};
const chunk = (type, data) => {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(td));
  return Buffer.concat([len, td, crc]);
};

function png(width, height, rgba) {
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 6; // RGBA
  const raw = Buffer.alloc(height * (1 + width * 4));
  for (let y = 0; y < height; y++) {
    raw[y * (1 + width * 4)] = 0;
    rgba.copy(raw, y * (1 + width * 4) + 1, y * width * 4, (y + 1) * width * 4);
  }
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw)),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

// Same interpolation as components/Gradient.tsx colorAt (clamped outside).
function alphaAt(stops, t) {
  if (t <= stops[0][0]) return stops[0][1];
  const last = stops[stops.length - 1];
  if (t >= last[0]) return last[1];
  for (let i = 1; i < stops.length; i++) {
    if (t <= stops[i][0]) {
      const [o0, a0] = stops[i - 1];
      const [o1, a1] = stops[i];
      return a0 + ((a1 - a0) * (t - o0)) / (o1 - o0);
    }
  }
  return last[1];
}

mkdirSync(join(dir, 'png'), {recursive: true});
const lines = [];
for (const [name, {color, stops}] of Object.entries(defs)) {
  const n = parseInt(color.slice(1), 16);
  const rgba = Buffer.alloc(STEPS * 4);
  for (let i = 0; i < STEPS; i++) {
    rgba[i * 4] = (n >> 16) & 255;
    rgba[i * 4 + 1] = (n >> 8) & 255;
    rgba[i * 4 + 2] = n & 255;
    rgba[i * 4 + 3] = Math.round(alphaAt(stops, (i + 0.5) / STEPS) * 255);
  }
  writeFileSync(join(dir, 'png', `${name}-v.png`), png(1, STEPS, rgba));
  writeFileSync(join(dir, 'png', `${name}-h.png`), png(STEPS, 1, rgba));
  lines.push(`  ${name}: {v: require('./png/${name}-v.png'), h: require('./png/${name}-h.png')},`);
}
writeFileSync(
  join(dir, 'assets.ts'),
  `// Generated by scripts/gen-gradients.mjs from defs.json. Do not edit.\n/* eslint-disable */\nexport const GRADIENT_ASSETS = {\n${lines.join('\n')}\n} as const;\n`,
);
console.log(`${Object.keys(defs).length} gradients`);
